// TideWall 3D — The Last Light: an endless mode on a sandbar. One lighthouse on a hill of sand, creatures from every side,
// and a sea that really rises up the slope each tide, so there's less beach to stand on and shrinking dry land between you
// and the sharks. The lamp sweeps the water, drying and burning whatever it touches; a sailor who climbs up can aim it.
// It burns oil: from fishing, the fishmonger's try-pot and salvage. Let it go dark too long and the run is over.
// Every few tides a boss; after each boss the sea pulls right back, and for a minute you can run out to loot the wrecks.
// What you bring home buys the Keeper's Log's permanent upgrades (only for this mode: Part I's losses stay final).
//
// Generated by LighthouseBuilder (TideWall → Rebuild The Last Light) into its own scene. The numbers are GameDatabase.lastLight.
using System.Collections.Generic;
using System.IO;
using UnityEngine;

namespace TideWall
{
    public class Lighthouse : Level
    {
        public const string SceneName = "The Last Light", PartId = "lastlight";
        public enum Tide : byte { Slack, Flood, Boss, LowTide }

        [Tooltip("The lamp room, and the beam that turns from it")] public Transform lamp, beam;
        public Light beamLight;
        public float lampHeight = 12;

        public Tide State { get; private set; } = Tide.Slack;
        /// <summary>Tides survived so far (0 until the first flood).</summary>
        public int Wave { get; private set; }
        public float Hp { get; private set; } = 1;
        public float MaxHp { get; private set; } = 1;
        public float Oil { get; private set; }
        public float MaxOil { get; private set; } = 1;
        public float StateLeft { get; private set; }
        public float DarkLeft { get; private set; }
        public bool LampOn => Oil > 0;
        public Player Keeper { get; private set; }
        /// <summary>Lamp oil to bank in the Keeper's Log when the run ends.</summary>
        public int Banked { get; private set; }

        LastLightDef def;
        GameManager gm;
        int toSpawn, bossesBeaten;
        float spawnT, scorchT, waterTarget, tideRate = 1, power = 1, sweep;
        Vector3 beamDir = Vector3.forward;
        readonly List<GameObject> scattered = new();
        readonly List<FishingSpot> spots = new();
        bool warnedDark, warnedLow;
        MaterialPropertyBlock beamBlock;

        public override PhaseDefinition HoldLook => GameManager.I.DB.lastLight.look;
        public override string Heading()
        {
            string what = State switch { Tide.Slack => $"Slack water · {Mathf.CeilToInt(StateLeft)}s", Tide.Flood => $"{gm.EnemiesLeft} creatures", Tide.Boss => "BOSS", _ => $"Low tide · {Mathf.CeilToInt(StateLeft)}s to salvage" };
            return $"<b>The Last Light · Tide {Mathf.Max(1, Wave)}</b> · {what}";
        }
        public override string ReachedLine(Player p) => $"You kept the light through tide {Wave}, and bring home {Banked} lamp oil";
        public override Legacy RecordRun(int level, int kills) => Legacy.RecordLight(Wave, level, kills, Banked);

        public override void Init(GameDatabase db)
        {
            gm = GameManager.I;
            def = db.lastLight;
            Arena.WaterLevel = waterTarget = def.startWater;
            MaxHp = Hp = def.towerHp; MaxOil = Oil = def.oilTank;
        }

        /// <summary>Host/offline: the first slack water. The Keeper's Log's upgrades apply from here.</summary>
        public void Begin()
        {
            var log = Legacy.Load();
            float L(KeeperUpgradeKind k) => log.KeeperBonus(def, k);
            MaxHp = Hp = def.towerHp * (1 + L(KeeperUpgradeKind.TowerHp));
            MaxOil = Oil = def.oilTank * (1 + L(KeeperUpgradeKind.OilTank));
            power = 1 + L(KeeperUpgradeKind.LampPower);
            tideRate = 1 / (1 + L(KeeperUpgradeKind.SlowTide));
            gm.AddSandDollars(def.startSandDollars + Mathf.RoundToInt(L(KeeperUpgradeKind.Purse)));
            gm.Waves.Day = 1;
            Enter(Tide.Slack, def.firstSlackSeconds);
            gm.Banner("THE LAST LIGHT", "Keep the lamp burning. The sea is coming up.");
        }

        void Enter(Tide s, float seconds)
        {
            State = s; StateLeft = seconds;
            warnedLow = false;
            if (s == Tide.Slack) { ReviveFallen(); PlaceSpots(); }
        }

        void ReviveFallen()
        {
            foreach (var p in gm.Players.All) if (p.Simulated && (p.IsOut || p.IsDowned)) p.Respawn(SpawnPoint(p.Index));
        }

        void PlaceSpots()
        {
            spots.RemoveAll(s => s == null);
            for (int i = spots.Count; i < def.fishingSpots; i++)
                spots.Add(FishingSpot.Spawn(Quaternion.Euler(0, Random.Range(0, 360f), 0) * Vector3.forward));
        }

        void StartFlood()
        {
            Wave++;
            gm.Waves.RunWave = Wave;
            gm.Waves.Day = 1 + Wave / def.tidesPerDay;
            waterTarget = Mathf.Min(def.maxWater, def.startWater + Wave * def.risePerTide * tideRate);
            bool boss = def.bossEvery > 0 && Wave % def.bossEvery == 0;
            toSpawn = Mathf.RoundToInt(def.budgetBase + def.budgetPerTide * Wave);
            spawnT = 1;
            if (boss)
            {
                var bossDef = gm.DB.Enemy(def.bosses[Mathf.Min(bossesBeaten, def.bosses.Count - 1)]);
                if (bossDef != null)
                {
                    SpawnAtRing(bossDef);
                    gm.Banner(bossDef.displayName.ToUpperInvariant() + " RISES", "It's coming up out of the deep. Hold the light!");
                    Sfx.Play("horn", 1, .2f);
                    toSpawn /= 2;
                    Enter(Tide.Boss, 0);
                    return;
                }
            }
            gm.Banner($"TIDE {Wave}", "The water's coming up.");
            Sfx.Play("horn", .7f, .2f);
            Enter(Tide.Flood, def.floodSeconds);
        }

        void SpawnAtRing(EnemyDef e)
        {
            var at = Quaternion.Euler(0, Random.Range(0, 360f), 0) * Vector3.forward * def.spawnRadius;
            if (e.behaviour == EnemyBehaviour.Flyer) at.y = 9; else at.y = Arena.GroundAt(at);
            gm.Waves.SpawnExtra(e, at);
            Fx.Splash(new Vector3(at.x, Arena.WaterLevel, at.z), 8);
        }

        void SpawnFromSea(float dt)
        {
            if (toSpawn <= 0 || GameManager.Enemies.Count >= gm.DB.maxAlive) return;
            if ((spawnT -= dt) > 0) return;
            spawnT = Random.Range(.5f, def.spawnGap);
            var pool = gm.DB.enemies.FindAll(e => e.cost > 0 && e.behaviour != EnemyBehaviour.Boss && e.minDay <= gm.Waves.Day && e.minWave <= Wave + 3);
            if (pool.Count == 0) return;
            float total = 0;
            foreach (var e in pool) total += e.spawnWeight / (1 + e.cost * .5f);
            float r = Random.value * total;
            foreach (var e in pool)
            {
                r -= e.spawnWeight / (1 + e.cost * .5f);
                if (r > 0) continue;
                SpawnAtRing(e);
                toSpawn -= Mathf.Max(1, e.cost);
                return;
            }
        }

        protected override void Update()
        {
            base.Update();
            if (gm == null) return;
            float dt = Time.deltaTime;
            UpdateBeamLook(dt);
            if (Net.IsClient) { WaterVisualOnly(); return; }
            if (gm.State != GameState.Playing) return;

            Arena.WaterLevel = Mathf.MoveTowards(Arena.WaterLevel, waterTarget, dt * (State == Tide.LowTide ? def.lowTideRate : def.riseRate));
            if (Keeper != null && (Keeper.IsOut || Keeper.IsDowned)) SetKeeper(null);
            UpdateLamp(dt);

            StateLeft -= dt;
            switch (State)
            {
                case Tide.Slack:
                    if (StateLeft <= 0) StartFlood();
                    break;
                case Tide.Flood:
                    SpawnFromSea(dt);
                    if ((toSpawn <= 0 && GameManager.Enemies.Count == 0) || StateLeft <= 0) { Banked += def.oilPerTide; Enter(Tide.Slack, def.slackSeconds); }
                    break;
                case Tide.Boss:
                    SpawnFromSea(dt);
                    if (toSpawn <= 0 && GameManager.Enemies.Count == 0) StartLowTide();
                    break;
                case Tide.LowTide:
                    if (!warnedLow && StateLeft < def.lowTideWarning) { warnedLow = true; gm.Banner("THE TIDE IS TURNING", "Back to high ground!"); Sfx.Play("horn"); }
                    if (StateLeft <= 0) EndLowTide();
                    break;
            }
        }

        void WaterVisualOnly() { }

        /// <summary>Tests and the capture: jump the mode along.</summary>
        public void StartFloodForTests() { StartFlood(); }
        public void StartLowTideForTests() { StartLowTide(); }
        public void EndLowTideForTests() { EndLowTide(); }
        public void SetDarkForTests(float seconds) { warnedDark = true; DarkLeft = seconds; }

        // ------------------------------------------------------------------ salvage: after each boss, the sea pulls back
        void StartLowTide()
        {
            bossesBeaten++;
            Banked += def.oilPerBoss;
            waterTarget = def.lowTideWater;
            Enter(Tide.LowTide, def.lowTideSeconds);
            gm.Banner("THE SEA PULLS BACK", "The wrecks are showing. Grab what you can before it comes home!");
            ReviveFallen();
            Sfx.Play("splash", 1, .2f);
            for (int i = 0; i < def.salvageCrates; i++)
            {
                float a = (i + Random.value * .7f) / def.salvageCrates * 360;
                var at = Quaternion.Euler(0, a, 0) * Vector3.forward * Random.Range(def.salvageRadius.x, def.salvageRadius.y);
                at.y = Arena.GroundAt(at);
                scattered.Add(SalvageCrate.Spawn(at).gameObject);
                if (i % 2 == 0 && gm.DB.Enemy("crab") is { } crab)
                    for (int k = 0; k < def.salvageGuards; k++)
                    {
                        var g = at + Quaternion.Euler(0, k * 120, 0) * Vector3.forward * 3;
                        g.y = Arena.GroundAt(g);
                        gm.Waves.SpawnExtra(crab, g);
                    }
            }
        }

        void EndLowTide()
        {
            waterTarget = Mathf.Min(def.maxWater, def.startWater + Wave * def.risePerTide * tideRate);
            foreach (var o in scattered) if (o != null) Destroy(o);
            scattered.Clear();
            Enter(Tide.Slack, def.slackSeconds);
        }

        /// <summary>A wreck opened: what's inside.</summary>
        public void Loot(Player p, Vector3 at)
        {
            float r = Random.value;
            int sd = Mathf.RoundToInt(Random.Range(def.salvageSandDollars.x, def.salvageSandDollars.y) * (1 + Wave * .05f));
            gm.AddSandDollars(sd, at, "salvage");
            string also = "";
            if (r < def.salvagePearlChance) { gm.AddPearls(1, at); also = " and a golden pearl"; }
            else if (r < def.salvagePearlChance + def.salvagePartChance)
            {
                var missing = gm.DB.attachments.FindAll(a => !p.OwnsPart(a.id));
                if (missing.Count > 0)
                {
                    var part = missing[Random.Range(0, missing.Count)];
                    p.OwnedParts.Add(part.id);
                    also = $" and a {part.displayName} (Inventory)";
                }
            }
            else { AddOil(def.salvageOil); also = " and a drum of lamp oil"; }
            p.Toast($"Salvage: {sd} SD{also}", new Color(1, .9f, .55f));
        }

        // ------------------------------------------------------------------ the lamp
        public void AddOil(float amount)
        {
            Oil = Mathf.Clamp(Oil + amount, 0, MaxOil);
            if (Oil > 0) { DarkLeft = 0; warnedDark = false; }
        }

        public void SetKeeper(Player p)
        {
            if (Keeper != null && Keeper != p) Keeper.SetPerch(0);
            Keeper = p;
            if (p != null) p.SetPerch(lampHeight);
        }

        void UpdateLamp(float dt)
        {
            bool burning = State != Tide.Slack || Keeper != null;
            if (burning && Oil > 0) Oil = Mathf.Max(0, Oil - dt * (Keeper != null ? def.oilBurnManned : def.oilBurnSweep));
            if (Oil <= 0 && State != Tide.Slack && State != Tide.LowTide)
            {
                if (!warnedDark) { warnedDark = true; DarkLeft = def.darkSeconds; gm.Banner("THE LIGHT IS OUT", $"Find oil. {def.darkSeconds:0} seconds."); Sfx.Play("horn"); }
                DarkLeft -= dt;
                if (DarkLeft <= 0) { gm.GameOver("The light went out."); return; }
            }
            sweep += dt * def.sweepSpeed;
            if (Keeper != null)
            {
                var d = Keeper.AimPoint - lamp.position;
                if (d.sqrMagnitude > .01f) beamDir = Vector3.Slerp(beamDir, d.normalized, 1 - Mathf.Exp(-dt * 12));
            }
            else beamDir = Quaternion.Euler(def.sweepPitch, sweep, 0) * Vector3.forward;
            if (Oil <= 0 || (scorchT -= dt) > 0) return;
            scorchT = .2f;
            float cone = Keeper != null ? def.coneManned : def.coneSweep;
            float mult = (Keeper != null ? def.mannedPower : 1) * power;
            var flat = new Vector3(beamDir.x, 0, beamDir.z).normalized;
            foreach (var e in GameManager.Enemies)
            {
                if (e == null || e.Dead) continue;
                var to = e.transform.position; to.y = 0;
                var aim = Keeper != null ? Keeper.AimPoint : Vector3.zero;
                if (to.magnitude > def.beamRange || (Keeper != null && Vector3.Distance(new Vector3(aim.x, 0, aim.z), to) > cone * .25f && Vector3.Angle(flat, to) > cone)) continue;
                if (Vector3.Angle(flat, to) > cone) continue;
                e.Scorch(def.beamDry * .2f, def.beamBurn * mult * .2f, def.beamSlow, Keeper);
            }
        }

        void UpdateBeamLook(float dt)
        {
            if (beam == null) return;
            bool lit = Oil > 0;
            if (beam.gameObject.activeSelf != lit) beam.gameObject.SetActive(lit);
            if (!lit) { if (beamLight) beamLight.enabled = false; return; }
            beam.rotation = Quaternion.LookRotation(beamDir);
            float width = (Keeper != null ? def.coneManned : def.coneSweep) * Mathf.Deg2Rad * 2 * def.beamRange;
            beam.localScale = new Vector3(width, width * .5f, def.beamRange);
            if (beamBlock == null)
            {
                beamBlock = new MaterialPropertyBlock();
                beamBlock.SetColor("_BaseColor", new Color(1, .9f, .6f, .16f));
                foreach (var r in beam.GetComponentsInChildren<Renderer>()) r.SetPropertyBlock(beamBlock);
            }
            if (beamLight)
            {
                beamLight.enabled = true;
                beamLight.transform.rotation = Quaternion.LookRotation(beamDir);
                beamLight.spotAngle = Mathf.Min(70, (Keeper != null ? def.coneManned : def.coneSweep) * 2.4f);
            }
        }

        // ------------------------------------------------------------------ what the sea attacks
        public override void DamageObjective(float amount, Vector3 where)
        {
            if (gm.State != GameState.Playing || Net.IsClient || amount <= 0) return;
            Hp = Mathf.Max(0, Hp - amount);
            Fx.Debris(where + Vector3.up, new Color(.8f, .75f, .7f), 3);
            Sfx.Play("thud", .4f, .1f);
            if (Hp <= 0) gm.GameOver("The lighthouse fell.");
        }
        public override bool AtObjective(Vector3 pos, float reach) { pos.y = 0; return pos.magnitude <= def.towerRadius + reach; }
        public void Repair(float amount) => Hp = Mathf.Min(MaxHp, Hp + amount);

        public override void OnCorpseSold(int value) => AddOil(value * def.oilPerCorpseValue);
        public override void OnFishCaught(FishDef f) => AddOil(f.oil);

        // ------------------------------------------------------------------ Level
        public override Vector3 Goal(Vector3 from, float radius, out GoalKind kind)
        {
            kind = GoalKind.Objective;
            var d = from; d.y = 0;
            if (d.sqrMagnitude < .01f) d = Vector3.forward;
            return d.normalized * (def.towerRadius + radius);
        }
        public override Vector3 FlyerTarget(Vector3 from) => Vector3.up * lampHeight * .7f;
        public override Vector3 SpawnPoint(int index)
        {
            var at = Quaternion.Euler(0, 45 + index * 90, 0) * Vector3.forward * (def.towerRadius + 3.5f);
            at.y = Arena.GroundAt(at) + .1f;
            return at;
        }
        public override string BuildRule(Vector3 spot, float radius)
        {
            var d = spot; d.y = 0;
            if (d.magnitude < def.towerRadius + radius + 1) return "Too close to the lighthouse";
            if (Arena.InWater(spot)) return "It would wash away";
            return null;
        }
        public override string StatusLine()
        {
            string oil = Oil > 0 ? $"Oil {Mathf.CeilToInt(Oil)}/{Mathf.RoundToInt(MaxOil)}" : $"<color=#fca5a5>LIGHT OUT {Mathf.CeilToInt(DarkLeft)}s</color>";
            return $"Lighthouse {Mathf.CeilToInt(Hp)}/{Mathf.RoundToInt(MaxHp)} · {oil} · Sea {Arena.ShoreRadius():0} m out";
        }
        public override float StatusFraction() => Mathf.Clamp01(Hp / Mathf.Max(1, MaxHp));

        // ------------------------------------------------------------------ online
        public override void WriteNet(BinaryWriter w)
        {
            w.Write((byte)State); w.Write((short)Wave); w.Write(Hp); w.Write(MaxHp); w.Write(Oil); w.Write(MaxOil); w.Write(StateLeft); w.Write(DarkLeft);
            w.Write(Arena.WaterLevel); w.Write(beamDir); w.Write((short)Banked); w.Write(Keeper != null);
        }

        public override void ReadNet(BinaryReader r)
        {
            State = (Tide)r.ReadByte(); Wave = r.ReadInt16(); Hp = r.ReadSingle(); MaxHp = r.ReadSingle(); Oil = r.ReadSingle(); MaxOil = r.ReadSingle();
            StateLeft = r.ReadSingle(); DarkLeft = r.ReadSingle(); Arena.WaterLevel = r.ReadSingle(); beamDir = r.ReadVector3(); Banked = r.ReadInt16();
            manned = r.ReadBoolean();
        }
        bool manned;
    }
